TEST(sandbox, writes_the_seatbelt_profile)
{
    sandbox_spec spec;
    spec.writable = {"/w/work", "/private/var/folders/x/T"};
    spec.writable_files = {"/c/tmp/1/jobserver"};
    spec.denied_reads = {"/Users/me"};
    spec.readable = {"/Users/me/Library/Caches/otok", "/Users/me/my \"recipes\""};
    EXPECT_EQ(seatbelt_profile(spec),
        "; Generated by otok: the sandbox of a build (docs/PLAN.md decision 28).\n"
        "(version 1)\n"
        "(allow default)\n"
        "(deny network*)\n"
        "(allow network* (remote unix-socket))\n"
        "(deny file-write*)\n"
        "(allow file-write*\n"
        "    (subpath \"/dev\")\n"
        "    (subpath \"/w/work\")\n"
        "    (subpath \"/private/var/folders/x/T\")\n"
        "    (literal \"/c/tmp/1/jobserver\"))\n"
        "(deny file-read-data\n"
        "    (subpath \"/Users/me\"))\n"
        "(allow file-read-data\n"
        "    (subpath \"/Users/me/Library/Caches/otok\")\n"
        "    (subpath \"/Users/me/my \\\"recipes\\\"\")\n"
        "    (subpath \"/w/work\")\n"
        "    (subpath \"/private/var/folders/x/T\")\n"
        "    (literal \"/c/tmp/1/jobserver\"))\n");

    host_sandbox const seatbelt{host_sandbox::mechanism::seatbelt, "/usr/bin/sandbox-exec", {}};
    EXPECT_EQ(sandbox_command(seatbelt, spec, "/w/work/sandbox.sb"), (std::vector<std::string>{"/usr/bin/sandbox-exec", "-f", "/w/work/sandbox.sb"}));
}

TEST(sandbox, writes_the_options_of_bubblewrap)
{
    sandbox_spec spec;
    spec.writable = {"/home/me/.cache/otok/tmp/1/build/a"};
    spec.writable_files = {"/home/me/.cache/otok/tmp/1/jobserver-1"};
    spec.denied_reads = {"/home/me"};
    // the NDK outside HOME is readable anyway
    spec.readable = {"/home/me/.cache/otok", "/home/me/my recipes", "/opt/ndk"};
    std::vector<std::string> const options{"--ro-bind", "/", "/", "--dev", "/dev", "--proc", "/proc", "--tmpfs", "/home/me",
        "--ro-bind-try", "/home/me/.cache/otok", "/home/me/.cache/otok", "--ro-bind-try", "/home/me/my recipes", "/home/me/my recipes",
        "--bind", "/home/me/.cache/otok/tmp/1/build/a", "/home/me/.cache/otok/tmp/1/build/a",
        "--bind", "/home/me/.cache/otok/tmp/1/jobserver-1", "/home/me/.cache/otok/tmp/1/jobserver-1",
        "--remount-ro", "/home/me", "--unshare-net", "--unshare-pid", "--die-with-parent", "--"};
    EXPECT_EQ(bubblewrap_args(spec), options);

    host_sandbox const bubblewrap{host_sandbox::mechanism::bubblewrap, "/usr/bin/bwrap", {}};
    std::vector<std::string> command{"/usr/bin/bwrap"};
    command.insert(command.end(), options.begin(), options.end());
    EXPECT_EQ(sandbox_command(bubblewrap, spec, "/unused/sandbox.sb"), command);
}

