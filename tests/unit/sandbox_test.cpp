TEST(sandbox, confines_processes)
{
    env_vars const env{{"PATH", "/usr/bin:/bin"}};
    host_sandbox const host = find_host_sandbox(env);
#ifdef __APPLE__
    ASSERT_EQ(host.kind, host_sandbox::mechanism::seatbelt);
#else
    if (host.kind == host_sandbox::mechanism::none) GTEST_SKIP() << host.why_not;
#endif
    test::temp_dir dir;
    std::filesystem::path const root = std::filesystem::canonical(dir.path());
    dir.write("work/mine.txt", "mine\n");
    dir.write("secret/key.txt", "secret\n");
    sandbox_spec spec;
    spec.writable = {root / "work"};
    spec.denied_reads = {root};
    std::filesystem::path const profile = root / "work" / "sandbox.sb";
    ASSERT_TRUE(write_file_atomic(profile, seatbelt_profile(spec)));

    auto const run = [&](std::vector<std::string> argv) {
        std::vector<std::string> command = sandbox_command(host, spec, profile);
        command.insert(command.end(), argv.begin(), argv.end());
        auto exit = run_process({command, env, root / "work", root / "work" / "log.txt", true});
        EXPECT_TRUE(exit) << exit.error().message;
        return exit ? exit->output : std::string{"?"};
    };
    // macOS refuses the connection; Linux has no route but loopback in the sandbox's network namespace
    std::string const connect = "use IO::Socket::INET; IO::Socket::INET->new(PeerAddr => '192.0.2.1:80', Timeout => 5) or print \"$!\"";
#ifdef __APPLE__
    EXPECT_EQ(run({"/usr/bin/perl", "-e", connect}), "Operation not permitted");
#else
    // strerror(ENETUNREACH) of perl's C library: glibc's, or musl's (Alpine)
    std::string const refused = run({"/usr/bin/perl", "-e", connect});
    EXPECT_TRUE(refused == "Network is unreachable" || refused == "Network unreachable") << refused;
#endif

    EXPECT_EQ(run({"/bin/sh", "-c", "echo x > made.txt && cat mine.txt made.txt"}), "mine\nx\n");
    run({"/bin/sh", "-c", "echo x > ../escaped.txt"});
    EXPECT_FALSE(std::filesystem::exists(root / "escaped.txt"));
    EXPECT_EQ(run({"/bin/sh", "-c", "cat ../secret/key.txt || echo denied"}), "denied\n");
    // the working directory under a denied one is what it is outside
    EXPECT_EQ(run({"/bin/pwd", "-P"}), path_to_utf8(root / "work") + "\n");
}

