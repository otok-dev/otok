consumer_cmake_parts test_parts()
{
    consumer_cmake_parts parts;
    parts.target = "linux";
    parts.platform = "linux";
    parts.detect = "set(_otok_arch \"x86_64\")\n";
    parts.link_item = [](std::string const& name) { return "-l" + name; };
    parts.cxx_runtime = "-lstdc++";
    return parts;
}

