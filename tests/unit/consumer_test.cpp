// A dynamic library: the DLL and its import library, or the shared object and its SONAME; the C++ runtime is its own.
TEST(consumer, imports_dynamic_libraries)
{
    consumer_package p;
    p.architectures = {"x86_64", "arm64"};
    p.configurations = {"release", "debug"};
    p.libraries = {{"z_z", "z", "", true,
                       {{"z", "x86_64", "release", "z/lib/x86_64/z.lib", "z/bin/x86_64/z.dll", "", "", true},
                           {"z", "x86_64", "debug", "z/debug/lib/x86_64/z.lib", "z/debug/bin/x86_64/z.dll", "", "", true},
                           {"z", "arm64", "release", "z/lib/arm64/libz.so.1.3", "", "", "libz.so.1", true}},
                       {}, {}, true}};
    consumer_cmake_parts parts = test_parts();
    parts.runtime_dlls = true;
    std::string const text = consumer_cmake_config(p, parts);
    EXPECT_NE(text.find("add_library(otok::z_z SHARED IMPORTED)\nset_property(TARGET otok::z_z PROPERTY IMPORTED_CONFIGURATIONS RELEASE DEBUG)\n"
                        "set_property(TARGET otok::z_z PROPERTY MAP_IMPORTED_CONFIG_RELWITHDEBINFO RELEASE)\n"
                        "set_property(TARGET otok::z_z PROPERTY MAP_IMPORTED_CONFIG_MINSIZEREL RELEASE)\n"
                        "if(_otok_arch STREQUAL \"x86_64\")\n"
                        "  set_target_properties(otok::z_z PROPERTIES\n"
                        "    IMPORTED_LOCATION_RELEASE \"${_otok_dir}/z/bin/x86_64/z.dll\"\n"
                        "    IMPORTED_IMPLIB_RELEASE \"${_otok_dir}/z/lib/x86_64/z.lib\"\n"
                        "    IMPORTED_LOCATION_DEBUG \"${_otok_dir}/z/debug/bin/x86_64/z.dll\"\n"
                        "    IMPORTED_IMPLIB_DEBUG \"${_otok_dir}/z/debug/lib/x86_64/z.lib\")\n"
                        "endif()\n"
                        "if(_otok_arch STREQUAL \"arm64\")\n"
                        "  set_target_properties(otok::z_z PROPERTIES\n"
                        "    IMPORTED_LOCATION_RELEASE \"${_otok_dir}/z/lib/arm64/libz.so.1.3\"\n"
                        "    IMPORTED_SONAME_RELEASE \"libz.so.1\")\n"
                        "endif()\n"
                        "\n# the data files"),
        std::string::npos)
        << text;
    EXPECT_NE(text.find("function(otok_copy_runtime_dlls target)\n"
                        "  add_custom_command(TARGET ${target} POST_BUILD\n"
                        "    COMMAND \"${CMAKE_COMMAND}\" -E copy -t \"$<TARGET_FILE_DIR:${target}>\" $<TARGET_RUNTIME_DLLS:${target}>\n"
                        "    COMMAND_EXPAND_LISTS)\n"
                        "endfunction()\n"),
        std::string::npos)
        << text;
}

// The other configuration serves when one was not built; a target whose configurations do not mix refuses it.
TEST(consumer, maps_or_refuses_a_configuration_not_built)
{
    consumer_package p;
    p.architectures = {"x86_64"};
    p.configurations = {"debug"};
    p.libraries = {{"z_z", "z", "", false, {{"z", "x86_64", "debug", "z/debug/lib/x86_64/z.lib"}}, {}, {}, false}};
    consumer_cmake_parts parts = test_parts();
    std::string text = consumer_cmake_config(p, parts);
    EXPECT_NE(text.find("set_property(TARGET otok::z_z PROPERTY MAP_IMPORTED_CONFIG_RELEASE DEBUG)\n"
                        "set_property(TARGET otok::z_z PROPERTY MAP_IMPORTED_CONFIG_RELWITHDEBINFO DEBUG)\n"
                        "set_property(TARGET otok::z_z PROPERTY MAP_IMPORTED_CONFIG_MINSIZEREL DEBUG)\n"),
        std::string::npos)
        << text;
    EXPECT_EQ(text.find("get_property(_otok_multi"), std::string::npos);

    parts.target = "windows";
    parts.strict_configurations = true;
    parts.not_built_suffix = ".lib";
    text = consumer_cmake_config(p, parts);
    EXPECT_NE(text.find("get_property(_otok_multi GLOBAL PROPERTY GENERATOR_IS_MULTI_CONFIG)\n"
                        "if(NOT _otok_multi)\n"
                        "  string(TOUPPER \"${CMAKE_BUILD_TYPE}\" _otok_build_type)\n"
                        "  if(NOT _otok_build_type STREQUAL \"DEBUG\")\n"
                        "    message(FATAL_ERROR \"otok: ${_otok_dir} has no libraries of the configuration 'release', which the build type "
                        "'${CMAKE_BUILD_TYPE}' links with: add \\\"release\\\" to 'configurations' of [windows] in otok.toml and run otok install\")\n"
                        "  endif()\n"
                        "endif()\n"
                        "if(_otok_multi)\n"
                        "  set(_otok_not_built \"$<$<NOT:$<CONFIG:Debug>>:${_otok_dir}/otok-has-no-release-libraries--add-release-to-configurations-of-windows-in-"
                        "otok.toml.lib>\")\n"
                        "endif()\n"),
        std::string::npos)
        << text;
    EXPECT_NE(text.find("set_property(TARGET otok::z_z PROPERTY INTERFACE_LINK_LIBRARIES ${_otok_not_built})\n"), std::string::npos) << text;
}

// The example of otok-toml.md 4.11.
TEST(consumer, reads_the_example_of_the_format)
{
    auto files = read_package_files(path_from_utf8(OTOK_TEST_DATA_DIR "/consumer"));
    ASSERT_TRUE(files) << files.error().message;
    EXPECT_EQ(files->properties, (std::map<std::string, std::string>{{"crt", "14.44"}}));
    ASSERT_EQ(files->files.size(), 1u);
    EXPECT_EQ(files->files[0], (package_library_file{"lz4", "x86_64", "release", "lib/x86_64/lz4.lib", "bin/x86_64/lz4.dll", "bin/x86_64/lz4.pdb", "", true}));
    // the file otok writes is the example (whose checkout may have CRLF line ends)
    std::string example = read_file(path_from_utf8(OTOK_TEST_DATA_DIR "/consumer/otok-package.toml")).value_or("");
    std::erase(example, '\r');
    EXPECT_EQ(write_package_files(*files), example);
}
