// Whether a Package.swift depends on other packages (a `.package(` call): a recipe delivers only a package
// without dependencies (recipe-toml.md 12.1).
bool has_package_dependencies(std::string_view manifest);

// A source target of Package.swift: a shim or a wrapper (otok-toml.md 4).
struct swift_target
{
    std::string name, path;
    std::vector<std::string> dependencies;
    // written as they are: `.copy("PrivacyInfo.xcprivacy")`, `.define("X")`, `.linkedLibrary("z")`
    std::vector<std::string> resources, c_settings, swift_settings, linker_settings;
    std::vector<std::pair<std::string, std::string>> product_dependencies{};   // product, package
};

// Package.swift of the output (otok-toml.md 4, DESIGN 5.5).
struct swift_package
{
    std::string tools_version;                                                  // "5.9"
    std::vector<std::pair<std::string, std::string>> platforms;                 // ".iOS", "16.0"
    std::vector<std::pair<std::string, std::vector<std::string>>> products;     // name, targets
    std::vector<std::pair<std::string, std::string>> binary_targets;            // name, path
    std::vector<swift_target> targets;
    std::vector<std::string> package_paths;                                     // local packages it depends on
};

std::string package_swift(swift_package const& package);

// A product of otok-config.cmake (otok-toml.md 4): the interface target `otok::<name>`.
struct cmake_product
{
    std::string name;
    std::vector<std::string> libraries;      // the XCFrameworks' targets, without `otok::`
    std::vector<std::string> include_dirs;   // relative to the output
    std::vector<std::string> link;           // "-lz", "-framework CoreFoundation"
    std::vector<std::string> defines;        // `NAME` or `NAME=value`
};

// otok-config.cmake of the output (otok-toml.md 4, docs/PLAN.md decision 92).
struct cmake_package
{
    std::vector<std::string> slices;                                   // "ios", "ios-simulator", "macos": what every XCFramework has
    std::vector<std::pair<std::string, std::string>> libraries;        // target name, the XCFramework relative to the output
    std::set<std::string> shared;                                      // the targets of dynamic libraries (otok-toml.md 4.10)
    std::vector<std::string> frameworks;                               // their XCFrameworks, relative to the output
    std::vector<std::string> macos_frameworks;                         // the directories of their macOS frameworks
    std::vector<cmake_product> products;
    std::vector<std::string> privacy_manifests;                        // relative to the output
    std::vector<std::pair<std::string, std::string>> data_dirs;        // library → its data/, relative to the output
    std::vector<std::string> warnings;                                 // what CMake's consumers do not get
};

std::string cmake_config(cmake_package const& package);

// The platform of an XCFramework's library identifier as the file checks it: "ios-arm64_x86_64-simulator" is
// "ios-simulator", "macos-arm64" "macos"; nothing when it is not one.
std::optional<std::string> cmake_slice_of(std::string_view identifier);

// The framework of a dynamic library (otok-toml.md 4.10): versioned (Versions/A/) on macOS and Mac Catalyst.
bool versioned_framework(std::string_view platform);

// `@rpath/<name>.framework/<name>`, `@rpath/<name>.framework/Versions/A/<name>` when versioned.
std::string framework_install_name(std::string const& name, bool versioned);

// `<prefix>.<library>.<output>`, every character other than a letter, a digit, '-' or '.' as '-'.
std::string bundle_identifier(std::string_view prefix, std::string_view library, std::string_view output);

// CFBundleShortVersionString of a library's version: up to its third numeric component, "0" without a leading number.
std::string bundle_short_version(std::string_view version);

// CFBundleSupportedPlatforms of a platform: "iPhoneOS", "iPhoneSimulator", "MacOSX", …
std::string supported_platform_of(std::string_view platform);

struct framework_plist
{
    std::string name, identifier, short_version, version, supported_platform;
    std::string minimum_key, minimum;   // "MinimumOSVersion", "16.0"; none when empty (Mac Catalyst)
};

std::string framework_info_plist(framework_plist const& p);

// Acknowledgements.plist: a Settings.bundle page (otok-toml.md 4).
std::string acknowledgements_plist(std::span<output_package const> packages);

