std::string tools_file_text(std::span<delivered_tool const> tools)
{
    std::string text = "# Generated by otok; do not edit. The programs of the tools with 'deliver' in otok.toml (otok-toml.md 7.1),\n"
                       "# relative to this file.\nformat = 1\n";
    for (delivered_tool const& t : tools) {
        text += "\n[programs.\"" + t.library + "\"]\n";
        for (auto const& [program, path] : t.programs) text += "\"" + program + "\" = \"" + t.library + "/" + path + "\"\n";
    }
    return text;
}

std::string tool_variable_name(std::string_view program)
{
    std::string name{program};
    for (char& c : name) {
        bool const kept = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9') || c == '_';
        if (!kept) c = '_';
    }
    return name;
}

namespace {

// A path relative to the file as MSBuild reads it in a property: `\`, and XML's and MSBuild's special characters escaped
// (MSBuild's as %XX).
std::string msbuild_path(std::string_view path)
{
    static constexpr char hex[] = "0123456789abcdef";
    std::string text;
    for (char const c : path) {
        switch (c) {
        case '/': text += '\\'; break;
        case '&': text += "&amp;"; break;
        case '<': text += "&lt;"; break;
        case '>': text += "&gt;"; break;
        case '%': case '$': case '@': case '\'': case ';': case '?': case '*':
            text += '%';
            text += hex[static_cast<unsigned char>(c) >> 4];
            text += hex[static_cast<unsigned char>(c) & 0xf];
            break;
        default: text += c;
        }
    }
    return text;
}

}

std::string tools_msbuild_text(std::span<delivered_tool const> tools)
{
    std::string text = "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n"
                       "<!-- Generated by otok; do not edit. The programs of the tools with 'deliver' in otok.toml (otok-toml.md 7.1):\n"
                       "     import this file from the project or its Directory.Build.props. -->\n"
                       "<Project>\n  <PropertyGroup>\n";
    for (delivered_tool const& t : tools) {
        for (auto const& [program, path] : t.programs) {
            std::string const name = "OtokTool_" + tool_variable_name(program);
            text += "    <" + name + ">$(MSBuildThisFileDirectory)" + msbuild_path(t.library + "/" + path) + "</" + name + ">\n";
        }
    }
    text += "  </PropertyGroup>\n</Project>\n";
    return text;
}

std::string tools_cmake_text(std::span<delivered_tool const> tools)
{
    std::string text = "# Generated by otok; do not edit. The programs of the tools with 'deliver' in otok.toml (otok-toml.md 7.1):\n"
                       "# include() this file.\n";
    for (delivered_tool const& t : tools) {
        for (auto const& [program, path] : t.programs) {
            std::string const quoted = cmake_quoted(t.library + "/" + path);
            text += "set(Otok_TOOL_" + tool_variable_name(program) + " \"${CMAKE_CURRENT_LIST_DIR}/" + quoted.substr(1) + ")\n";
        }
    }
    return text;
}

result<output_changes> write_tools_output(fs::path const& dir, std::span<delivered_tool const> tools)
{
    auto opened = open_output(dir, "tools-output");
    if (!opened) return std::unexpected{opened.error()};
    output_state state = std::move(*opened);
    fs::path const state_file = dir / output_state_file;
    std::error_code ec;
    std::map<std::string, delivered_tool const*> current;
    for (delivered_tool const& t : tools) current.emplace(t.library, &t);

    // as write_output: the state written after each step
    output_changes changes;
    for (auto it = state.begin(); it != state.end();) {
        if (current.contains(it->first)) {
            ++it;
            continue;
        }
        fs::remove_all(long_path(dir / path_from_utf8(it->first)), ec);
        if (ec) return fail("cannot remove '" + slashed(dir / path_from_utf8(it->first)) + "': " + ec.message());
        it = state.erase(it);
        ++changes.removed;
        if (auto ok = write_state(state_file, state); !ok) return std::unexpected{ok.error()};
    }
    for (auto const& [library, t] : current) {
        fs::path const out = dir / path_from_utf8(library);
        if (auto it = state.find(library); it != state.end() && it->second == t->key && fs::is_directory(long_path(out), ec)) {
            ++changes.unchanged;
            continue;
        }
        if (state.erase(library) > 0) {
            if (auto ok = write_state(state_file, state); !ok) return std::unexpected{ok.error()};
        }
        fs::remove_all(long_path(out), ec);
        if (ec) return fail("cannot remove '" + slashed(out) + "': " + ec.message());
        if (auto ok = copy_tree(t->prefix, out); !ok) return fail("cannot copy the tool '" + library + "' into '" + slashed(dir) + "': " + ok.error().message);
        state[library] = t->key;
        ++changes.copied;
        if (auto ok = write_state(state_file, state); !ok) return std::unexpected{ok.error()};
    }
    if (auto ok = write_state(state_file, state); !ok) return std::unexpected{ok.error()};
    std::vector<delivered_tool> sorted;
    for (auto const& [library, t] : current) sorted.push_back(*t);
    for (auto const& [file, text] : {std::pair{tools_file, tools_file_text(sorted)}, std::pair{tools_msbuild_file, tools_msbuild_text(sorted)},
             std::pair{tools_cmake_file, tools_cmake_text(sorted)}}) {
        if (auto ok = write_file_if_changed(dir / file, text); !ok) return std::unexpected{ok.error()};
    }
    return changes;
}

result<output_changes> write_output(fs::path const& dir, build_target const& target, std::span<packaged const> packages,
    std::map<std::string, std::string> const& deployment)
{
    std::string const name = slashed(dir);
    fs::path const state_file = dir / output_state_file;
    std::error_code ec;
    auto opened = open_output(dir, "output");
    if (!opened) return std::unexpected{opened.error()};
    output_state state = std::move(*opened);

    std::map<std::string, packaged const*> current;
    for (packaged const& p : packages) {
        if (p.target == target.info().name) current.emplace(p.library, &p);
    }

    // The state is written after each step, so an interrupted run leaves no directory it does not list
    // with its key, and the next run copies again what it did not finish.
    output_changes changes;
    auto const remove = [&](std::string const& library) -> result<void> {
        fs::path const out = dir / target.package_output(library);
        fs::remove_all(long_path(out), ec);
        if (ec) return fail("cannot remove '" + slashed(out) + "': " + ec.message());
        return {};
    };
    for (auto it = state.begin(); it != state.end();) {
        if (current.contains(it->first)) {
            ++it;
            continue;
        }
        if (auto ok = remove(it->first); !ok) return std::unexpected{ok.error()};
        it = state.erase(it);
        ++changes.removed;
        if (auto ok = write_state(state_file, state); !ok) return std::unexpected{ok.error()};
    }
    for (auto const& [library, p] : current) {
        fs::path const out = dir / target.package_output(library);
        if (auto it = state.find(library); it != state.end() && it->second == p->key && fs::is_directory(long_path(out), ec)) {
            ++changes.unchanged;
            continue;
        }
        if (state.erase(library) > 0) {
            if (auto ok = write_state(state_file, state); !ok) return std::unexpected{ok.error()};
        }
        if (auto ok = remove(library); !ok) return std::unexpected{ok.error()};
        if (auto ok = copy_tree(p->entry, out); !ok) return fail("cannot copy '" + library + "' into the output: " + ok.error().message);
        fs::remove(long_path(out / "key.txt"), ec);
        state[library] = p->key;
        ++changes.copied;
        if (auto ok = write_state(state_file, state); !ok) return std::unexpected{ok.error()};
    }
    if (auto ok = write_state(state_file, state); !ok) return std::unexpected{ok.error()};

    std::vector<output_package> outputs;
    for (auto const& [library, p] : current) {
        output_package o{library, p->rec, p->libraries, p->products, p->option_defines, {}, target.package_output(library), p->data, p->bundle_data, p->linkage};
        for (license_entry const& file : p->rec->license_files) {
            auto text = read_file(dir / o.dir / "licenses" / path_from_utf8(file.path));
            if (!text) return fail("the output '" + name + "': the license file '" + file.path + "' of '" + library + "': " + text.error().message);
            std::erase(*text, '\r');
            o.licenses.push_back({file.path, std::move(*text)});
        }
        outputs.push_back(std::move(o));
    }
    if (auto ok = write_file_if_changed(dir / "Acknowledgements.md", acknowledgements_markdown(outputs)); !ok) return std::unexpected{ok.error()};
    if (auto ok = target.finish_output(dir, outputs, deployment, changes.warnings); !ok) return fail("the output '" + name + "': " + ok.error().message);
    changes.problems = target.output_problems(dir, outputs, deployment, changes.warnings);
    return changes;
}

std::vector<option_define> option_defines(recipe const& rec, merged_options const& options)
{
    auto const identifier = [](std::string_view s) {
        std::string out;
        for (char c : s) {
            bool const alnum = (c >= 'a' && c <= 'z') || (c >= 'A' && c <= 'Z') || (c >= '0' && c <= '9');
            out += alnum ? static_cast<char>(c >= 'a' && c <= 'z' ? c - 'a' + 'A' : c) : '_';
        }
        return out;
    };
    std::vector<option_define> out;
    for (option_schema const& schema : rec.options) {
        auto const it = options.find(schema.name);
        if (it == options.end()) continue;
        std::string const name = "OTOK_OPTION_" + identifier(schema.name);
        option_data const& value = it->second;
        switch (schema.type) {
        case option_type::boolean:
            if (std::get<bool>(value)) out.push_back({name, std::nullopt});
            break;
        case option_type::integer:
            out.push_back({name, std::to_string(std::get<std::int64_t>(value))});
            break;
        case option_type::string: {
            std::string literal = "\"";
            for (char c : std::get<std::string>(value)) {
                if (c == '"' || c == '\\') literal += '\\';
                literal += c;
            }
            out.push_back({name, literal + "\""});
            break;
        }
        case option_type::enumeration:
            out.push_back({name + "_" + identifier(std::get<std::string>(value)), std::nullopt});
            break;
        case option_type::list:
            for (std::string const& element : std::get<std::vector<std::string>>(value)) out.push_back({name + "_" + identifier(element), std::nullopt});
            break;
        case option_type::file:
            if (!std::get<std::string>(value).empty()) out.push_back({name, std::nullopt});
            break;
        }
    }
    return out;
}

std::string acknowledgements_markdown(std::span<output_package const> packages)
{
    std::string text = "<!-- Generated by otok; do not edit. -->\n# Acknowledgements\n\nThis product includes the following libraries.\n";
    for (output_package const& p : packages) {
        text += "\n## " + p.library + " " + p.rec->version->str() + "\n\nLicense: " + p.rec->license_text + "\n";
        for (license_file const& f : p.licenses) {
            std::string body = f.text;
            while (!body.empty() && (body.back() == '\n' || body.back() == ' ')) body.pop_back();
            text += "\n```text\n" + body + "\n```\n";
        }
    }
    return text;
}

