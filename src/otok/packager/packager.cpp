// The libraries of a package built for `target`; empty when it was not.
std::vector<library_ref> libraries_on(std::string const& library, build_target const& target, std::span<built_package const> built)
{
    std::vector<library_ref> refs;
    for (built_package const& bp : built) {
        if (bp.tool || bp.library != library) continue;
        for (built_slice const& s : bp.slices) {
            if (!target.info().find_platform(s.spec.platform)) continue;
            for (auto const& [name, path] : s.output.libraries) refs.push_back({library, name});
            return refs;
        }
    }
    return refs;
}

void append_unique(std::vector<library_ref>& to, std::vector<library_ref> const& from)
{
    for (library_ref const& l : from) {
        if (std::ranges::find(to, l) == to.end()) to.push_back(l);
    }
}

// Whether a package was built for `target`.
bool built_on(std::string const& library, build_target const& target, std::span<built_package const> built)
{
    for (built_package const& bp : built) {
        if (bp.tool || bp.library != library) continue;
        for (built_slice const& s : bp.slices) {
            if (target.info().find_platform(s.spec.platform)) return true;
        }
    }
    return false;
}

// Whether `of` depends on `d` on this target: `d` has no `when`, or it holds on a platform `of` was
// built for (recipe-toml.md 9.1). The library being built is not enough: the project may name it too.
bool dependency_holds(recipe_dependency const& d, resolved_package const& of, std::size_t configuration, build_target const& target,
    std::span<built_package const> built)
{
    if (!d.when) return true;
    merged_options const& options = of.configurations[configuration].options;
    for (built_package const& bp : built) {
        if (bp.tool || bp.library != of.library) continue;
        for (built_slice const& s : bp.slices) {
            if (!target.info().find_platform(s.spec.platform)) continue;
            if (condition_holds(*d.when, options, target.info().name, s.spec.platform)) return true;
        }
    }
    return false;
}

// The products of a package whose `when` holds, each with the libraries it holds (otok-toml.md 4): its
// own, those of the products it depends on, and every library of the recipe's dependencies built for
// the target whose `when` holds, transitively; and so the products of headers only among them
// (recipe-toml.md 11.1).
result<std::vector<output_product>> products_on(resolved_package const& p, std::size_t configuration, build_target const& target,
    resolution const& r, std::span<built_package const> built)
{
    recipe const& rec = *p.chosen.recipe;
    merged_options const& options = p.configurations[configuration].options;

    std::vector<library_ref> dependencies, dependency_headers;
    std::set<std::string> seen;
    auto const visit = [&](auto& self, resolved_package const& of) -> void {
        for (recipe_dependency const& d : of.chosen.recipe->dependencies) {
            resolved_package const* dp = r.find(d.library, p.target);
            if (!dp || !built_on(d.library, target, built) || !dependency_holds(d, of, configuration, target, built)) continue;
            if (!seen.insert(d.library).second) continue;
            append_unique(dependencies, libraries_on(d.library, target, built));
            for (product const& prod : dp->chosen.recipe->products) {
                if (!prod.headers_only()) continue;
                if (prod.when && !condition_holds(*prod.when, dp->configurations[configuration].options, target.info().name, "")) continue;
                append_unique(dependency_headers, {{d.library, prod.name}});
            }
            self(self, *dp);
        }
    };
    visit(visit, p);

    std::vector<output_product> out;
    for (product const& prod : rec.products) {
        if (prod.when && !condition_holds(*prod.when, options, target.info().name, "")) continue;
        output_product o{&prod, {}, {}};
        std::set<std::string> expanded;
        auto const expand = [&](auto& self, product const& of) -> result<void> {
            if (!expanded.insert(of.name).second) return {};
            if (of.headers_only() && !rec.delivers_sources) append_unique(o.header_products, {{p.library, of.name}});
            for (std::string const& name : of.libraries) append_unique(o.libraries, {{p.library, name}});
            for (std::string const& name : of.depends) {
                auto const it = std::ranges::find(rec.products, name, &product::name);
                if (it == rec.products.end()) return fail(rec.name + ": product '" + of.name + "' depends on the unknown product '" + name + "'");
                if (auto ok = self(self, *it); !ok) return ok;
            }
            return {};
        };
        if (auto ok = expand(expand, prod); !ok) return std::unexpected{ok.error()};
        append_unique(o.libraries, dependencies);
        append_unique(o.header_products, dependency_headers);
        for (product_define const& d : prod.defines) {
            if (!d.when || condition_holds(*d.when, options, target.info().name, "")) o.defines.push_back(d.define);
        }
        o.link = link_on(prod, options, target.info().name);
        out.push_back(std::move(o));
    }
    return out;
}

// The data files of the slices (build-lua-api.md 8) into `dir`: every slice returns the same names with the
// same contents, so one copy serves them all.
result<void> package_data(std::span<built_slice const> slices, fs::path const& dir)
{
    if (slices.empty()) return {};
    built_slice const& first = slices.front();
    std::error_code ec;
    for (auto const& [name, file] : first.output.data) {
        auto const hash = sha256_file(file);
        if (!hash) return fail("the data file '" + name + "': " + hash.error().message);
        for (built_slice const& s : slices) {
            auto const other = s.output.data.find(name);
            if (other == s.output.data.end()) return fail("the data file '" + name + "' of " + slice_label(first.spec) + " is missing in " + slice_label(s.spec));
            auto const other_hash = sha256_file(other->second);
            if (!other_hash) return fail("the data file '" + name + "': " + other_hash.error().message);
            if (*other_hash != *hash) {
                return fail("the data file '" + name + "' differs between " + slice_label(first.spec) + " and " + slice_label(s.spec)
                    + "; every slice must return the same data");
            }
        }
        fs::create_directories(long_path(dir), ec);
        fs::copy_file(long_path(file), long_path(dir / path_from_utf8(name)), fs::copy_options::overwrite_existing, ec);
        if (ec) return fail("cannot copy the data file '" + name + "': " + ec.message());
    }
    for (built_slice const& s : slices) {
        for (auto const& [name, file] : s.output.data) {
            if (!first.output.data.contains(name)) return fail("the data file '" + name + "' of " + slice_label(s.spec) + " is missing in " + slice_label(first.spec));
        }
    }
    return {};
}

