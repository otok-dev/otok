// Bumped when the meaning of a package key changes (cache-key.md 4), and the packager version, bumped
// when otok changes how it packages.
constexpr char const* key_format = "1";
constexpr char const* packager_version = "9";

constexpr int output_state_format = 1;

std::string slashed(fs::path const& p)
{
    return path_to_utf8(p.generic_u8string());
}

using output_state = std::map<std::string, std::string>;  // library → package key

result<output_state> read_state(fs::path const& file)
{
    auto content = read_file(file);
    if (!content) return fail(content.error().message);
    toml::table t;
    try {
        t = toml::parse(*content);
    } catch (toml::parse_error const& e) {
        return fail(std::string{e.description()});
    }
    if (t["format"].value<std::int64_t>() != output_state_format) return fail("unknown format");
    output_state state;
    if (toml::table const* packages = t["packages"].as_table()) {
        for (auto const& [library, key] : *packages) {
            auto s = key.value<std::string>();
            if (!s) return fail("the key of '" + std::string{library.str()} + "' is not a string");
            state.emplace(std::string{library.str()}, *s);
        }
    }
    return state;
}

result<void> write_state(fs::path const& file, output_state const& state)
{
    std::string text = "# Generated by otok; do not edit.\nformat = " + std::to_string(output_state_format) + "\n\n[packages]\n";
    for (auto const& [library, key] : state) text += library + " = \"" + key + "\"\n";
    return write_file_atomic(file, text);
}

