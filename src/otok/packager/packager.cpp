result<std::vector<packaged>> package_all(resolution const& r, std::size_t configuration, std::span<built_package const> built,
    std::span<build_target* const> targets, cache_store& cache, std::ostream& progress,
    std::function<void(std::string const& library, std::string const& target)> const& packaging)
{
    std::vector<packaged> out;
    for (built_package const& bp : built) {
        if (bp.tool) continue;
        resolved_package const* p = r.find_id(bp.id);
        if (!p) return fail(bp.id + " is not in the resolution");
        recipe const& rec = *p->chosen.recipe;
        std::string const version = rec.version->str() + "-r" + std::to_string(rec.revision);
        for (build_target* target : targets) {
            built_package mine{bp.library, false, bp.recipe_sha256, {}, bp.recipe_dir, bp.source, bp.sources, bp.sources_key, bp.bundle_data};
            for (built_slice const& s : bp.slices) {
                if (target->info().find_platform(s.spec.platform)) mine.slices.push_back(s);
            }
            if (rec.delivers_sources) {
                // no slices: the target takes the source when the project uses one of its platforms
                auto const& platforms = p->configurations[configuration].platforms;
                if (std::ranges::none_of(platforms, [&](std::string const& pl) { return target->info().find_platform(pl) != nullptr; })) continue;
            } else if (mine.slices.empty()) {
                continue;
            }

            std::map<std::string, std::string> key;
            key["key-format"] = key_format;
            key["packager"] = packager_version;
            key["os"] = target->info().name;
            key["library"] = bp.library;
            key["version"] = rec.version->str();
            key["revision"] = std::to_string(rec.revision);
            key["recipe-sha256"] = bp.recipe_sha256;
            // as the slice keys have them: a file option by its contents (cache-key.md 4)
            std::map<std::string, std::string> const* keyed = mine.slices.empty() ? nullptr : &mine.slices.front().option_keys;
            for (auto const& [name, value] : p->configurations[configuration].options) {
                std::string text = format_option_value(value);
                if (keyed) {
                    if (auto const it = keyed->find(name); it != keyed->end()) text = it->second;
                }
                key["option." + name] = std::move(text);
            }
            for (built_slice const& s : mine.slices) key["slice." + slice_name(s.spec) + "." + s.spec.configuration] = s.key;
            if (rec.delivers_sources) key["sources"] = bp.sources_key;
            if (bp.bundle_data) key["bundle-data"] = "true";
            // the target's choices that change the packages (cache-key.md 4)
            if (!mine.slices.empty()) {
                for (target_choice const& c : target->info().choices) {
                    if (!c.packaging) continue;
                    auto const value = mine.slices.front().spec.choices.find(c.key);
                    key["choice." + c.key] = value != mine.slices.front().spec.choices.end() ? value->second : c.values.front();
                }
            }
            std::string const text = key_text(key);

            packaged pk;
            pk.library = bp.library;
            pk.target = target->info().name;
            pk.key = sha256_hex(text);
            pk.entry = cache.root() / "builds" / bp.library / version / "packages" / pk.key.substr(0, 32);
            auto products = products_on(*p, configuration, *target, r, built);
            if (!products) return std::unexpected{products.error()};
            pk.products = std::move(*products);
            pk.option_defines = option_defines(rec, p->configurations[configuration].options);
            if (!mine.slices.empty()) {
                for (auto const& [name, file] : mine.slices.front().output.data) pk.data.push_back(name);
            }
            pk.bundle_data = bp.bundle_data;
            if (!mine.slices.empty()) pk.linkage = mine.slices.front().spec.linkage;

            std::error_code ec;
            pk.cached = fs::exists(long_path(pk.entry), ec);
            if (pk.cached) cache.mark_used(pk.entry);
            if (!pk.cached) {
                std::string const label = bp.library + " " + rec.version->str() + " for " + pk.target;
                progress << "packaging " << label << "\n";
                if (packaging) packaging(bp.library, pk.target);
                auto made = cache.ensure(pk.entry, "packaging " + label, [&](fs::path const& staging) -> result<void> {
                    fs::create_directories(long_path(staging), ec);
                    if (ec) return fail("cannot create '" + slashed(staging) + "': " + ec.message());
                    if (auto ok = target->make_package(mine, rec, pk.products, staging); !ok) return fail("packaging " + label + ": " + ok.error().message);
                    if (auto ok = package_data(mine.slices, staging / "data"); !ok) return fail("packaging " + label + ": " + ok.error().message);
                    for (license_entry const& file : rec.license_files) {
                        fs::path const to = staging / "licenses" / path_from_utf8(file.path);
                        fs::create_directories(long_path(to.parent_path()), ec);
                        fs::path const from = (file.in_recipe ? bp.recipe_dir : bp.source) / path_from_utf8(file.path);
                        fs::copy_file(long_path(from), long_path(to), fs::copy_options::overwrite_existing, ec);
                        if (ec) return fail("packaging " + label + ": cannot copy the license file '" + file.path + "': " + ec.message());
                    }
                    return write_file_atomic(staging / "key.txt", text);
                });
                if (!made) return std::unexpected{made.error()};
            }
            pk.rec = &rec;
            if (!mine.slices.empty()) {
                for (auto const& [name, path] : mine.slices.front().output.libraries) pk.libraries.push_back(name);
            }
            out.push_back(std::move(pk));
        }
    }
    return out;
}

result<std::map<std::string, std::string>> read_output_state(fs::path const& dir)
{
    fs::path const file = dir / output_state_file;
    std::error_code ec;
    if (!fs::exists(long_path(file), ec)) return output_state{};
    auto state = read_state(file);
    if (!state) return fail("the state file of the output '" + slashed(dir) + "' is damaged (" + state.error().message + ")");
    return state;
}

