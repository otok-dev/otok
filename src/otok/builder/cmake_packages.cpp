char const* const generated = "# Generated by otok; do not edit.\n";

std::string target_of(std::string const& product) { return "otok::" + product; }

std::string joined_targets(std::vector<std::string> const& products)
{
    std::string out;
    for (std::string const& p : products) out += " " + target_of(p);
    return out;
}

std::string quoted_list(std::vector<std::string> const& items)
{
    std::string out;
    for (std::string const& i : items) out += " " + cmake_quoted(i);
    return out;
}

// What a package of a library is, once the products in effect are known.
struct package_view
{
    output_package const* package;
    cmake_package_spec const* spec;
};

bool all_present(cmake_name const& n, std::set<std::string> const& present)
{
    return std::ranges::all_of(n.products, [&](std::string const& p) { return present.contains(p); });
}

std::string config_text(output_package const& o, cmake_package_spec const& spec, std::set<std::string> const& present)
{
    std::string const version = cmake_package_version(o.rec && o.rec->version ? o.rec->version->str() : std::string{});
    std::string const library = o.library;
    std::string text = std::string{generated}
        + "# The CMake package '" + spec.name + "' of the library " + library + " over the products of otok-config.cmake (otok-toml.md 4.12).\n\n"
          "set(_otok_name \"${CMAKE_FIND_PACKAGE_NAME}\")\n"
          "set(_otok_version " + cmake_quoted(version) + ")\n\n";

    // the version: refused here, not in the version file, so that CMake looks for the package nowhere else
    text += "# the version asked for: it or an older one, EXACT only it, a range holding it\n"
            "set(_otok_fits TRUE)\n"
            "set(_otok_asked \"\")\n"
            "if(NOT \"${${_otok_name}_FIND_VERSION_RANGE}\" STREQUAL \"\")\n"
            "  set(_otok_asked \"${${_otok_name}_FIND_VERSION_RANGE}\")\n"
            "elseif(NOT \"${${_otok_name}_FIND_VERSION}\" STREQUAL \"\")\n"
            "  set(_otok_asked \"${${_otok_name}_FIND_VERSION}\")\n"
            "endif()\n"
            "if(_otok_asked STREQUAL \"\")\n"
            "elseif(_otok_version STREQUAL \"\")\n"
            "  message(VERBOSE \"otok: the version ${_otok_asked} of ${_otok_name} is not checked: the version of " + library
        + " starts with no number\")\n"
          "elseif(NOT \"${${_otok_name}_FIND_VERSION_RANGE}\" STREQUAL \"\")\n"
          "  if(_otok_version VERSION_LESS \"${${_otok_name}_FIND_VERSION_MIN}\")\n"
          "    set(_otok_fits FALSE)\n"
          "  elseif(${_otok_name}_FIND_VERSION_RANGE_MAX STREQUAL \"INCLUDE\" AND _otok_version VERSION_GREATER \"${${_otok_name}_FIND_VERSION_MAX}\")\n"
          "    set(_otok_fits FALSE)\n"
          "  elseif(${_otok_name}_FIND_VERSION_RANGE_MAX STREQUAL \"EXCLUDE\" AND NOT _otok_version VERSION_LESS \"${${_otok_name}_FIND_VERSION_MAX}\")\n"
          "    set(_otok_fits FALSE)\n"
          "  endif()\n"
          "elseif(${_otok_name}_FIND_VERSION_EXACT)\n"
          "  if(NOT _otok_version VERSION_EQUAL \"${${_otok_name}_FIND_VERSION}\")\n"
          "    set(_otok_fits FALSE)\n"
          "  endif()\n"
          "elseif(_otok_version VERSION_LESS \"${${_otok_name}_FIND_VERSION}\")\n"
          "  set(_otok_fits FALSE)\n"
          "endif()\n"
          "if(NOT _otok_fits)\n"
          "  set(${_otok_name}_FOUND FALSE)\n"
          "  set(${_otok_name}_NOT_FOUND_MESSAGE \"otok: ${CMAKE_CURRENT_LIST_DIR} is " + library + " ${_otok_version}, not the version ${_otok_asked} asked for\")\n"
          "  unset(_otok_name)\n  unset(_otok_version)\n  unset(_otok_fits)\n  unset(_otok_asked)\n"
          "  return()\n"
          "endif()\n";

    // the components whose products are in effect
    std::vector<std::string> components;
    for (cmake_name const& c : spec.components) {
        if (all_present(c, present)) components.push_back(c.name);
    }
    text += "\n# the components, those whose products the output has\n"
            "set(_otok_components" + quoted_list(components) + ")\n"
            "set(_otok_missing \"\")\n"
            "foreach(_otok_component IN LISTS ${_otok_name}_FIND_COMPONENTS)\n"
            "  if(_otok_component IN_LIST _otok_components)\n"
            "    set(${_otok_name}_${_otok_component}_FOUND TRUE)\n"
            "  else()\n"
            "    set(${_otok_name}_${_otok_component}_FOUND FALSE)\n"
            "    if(${_otok_name}_FIND_REQUIRED_${_otok_component})\n"
            "      list(APPEND _otok_missing \"${_otok_component}\")\n"
            "    endif()\n"
            "  endif()\n"
            "endforeach()\n"
            "if(_otok_missing)\n"
            "  list(JOIN _otok_missing \", \" _otok_missing)\n"
            "  list(JOIN _otok_components \", \" _otok_components)\n"
            "  if(_otok_components STREQUAL \"\")\n"
            "    set(_otok_components \"none\")\n"
            "  endif()\n"
            "  set(${_otok_name}_FOUND FALSE)\n"
            "  set(${_otok_name}_NOT_FOUND_MESSAGE \"otok: ${CMAKE_CURRENT_LIST_DIR} has no component ${_otok_missing} of " + library
        + "; its products give: ${_otok_components} (otok-toml.md 4.12)\")\n"
          "  unset(_otok_name)\n  unset(_otok_version)\n  unset(_otok_fits)\n  unset(_otok_asked)\n  unset(_otok_components)\n  unset(_otok_missing)\n"
          "  return()\n"
          "endif()\n\n";

    text += "include(\"${CMAKE_CURRENT_LIST_DIR}/../../otok-config.cmake\")\n";

    // the targets whose products the output has
    std::vector<std::string> targets;
    text += "\n# the targets\n";
    for (cmake_name const& t : spec.targets) {
        if (!all_present(t, present)) continue;
        targets.push_back(t.name);
        text += "if(NOT TARGET " + t.name + ")\n"
                "  add_library(" + t.name + " INTERFACE IMPORTED)\n"
                "  set_property(TARGET " + t.name + " PROPERTY INTERFACE_LINK_LIBRARIES" + joined_targets(t.products) + ")\n"
                "endif()\n";
    }

    // the include directories of otok's targets a list holds, through the targets they link
    text += "\nif(NOT COMMAND _otok_cmake_include_dirs)\n"
            "  function(_otok_cmake_include_dirs out)\n"
            "    set(dirs \"\")\n"
            "    set(seen \"\")\n"
            "    set(queue ${ARGN})\n"
            "    while(queue)\n"
            "      list(POP_FRONT queue target)\n"
            "      if(target IN_LIST seen OR NOT TARGET \"${target}\")\n"
            "        continue()\n"
            "      endif()\n"
            "      list(APPEND seen \"${target}\")\n"
            "      get_target_property(found \"${target}\" INTERFACE_INCLUDE_DIRECTORIES)\n"
            "      if(found)\n"
            "        list(APPEND dirs ${found})\n"
            "      endif()\n"
            "      get_target_property(linked \"${target}\" INTERFACE_LINK_LIBRARIES)\n"
            "      foreach(item IN LISTS linked)\n"
            "        if(item MATCHES \"^otok::\")\n"
            "          list(APPEND queue \"${item}\")\n"
            "        endif()\n"
            "      endforeach()\n"
            "    endwhile()\n"
            "    list(REMOVE_DUPLICATES dirs)\n"
            "    set(${out} \"${dirs}\" PARENT_SCOPE)\n"
            "  endfunction()\n"
            "endif()\n";

    // the variables every package gets, under the package's names: as written, in upper case, as the call wrote it
    std::vector<std::string> products;  // of the targets defined
    for (cmake_name const& t : spec.targets) {
        if (!all_present(t, present)) continue;
        for (std::string const& p : t.products) {
            if (std::ranges::find(products, p) == products.end()) products.push_back(p);
        }
    }
    text += "\n# the variables\n"
            "_otok_cmake_include_dirs(_otok_include_dirs" + joined_targets(products) + ")\n"
            "set(_otok_prefixes " + cmake_quoted(spec.name) + " " + cmake_quoted(cmake_upper(spec.name)) + " \"${_otok_name}\")\n"
            "list(REMOVE_DUPLICATES _otok_prefixes)\n"
            "foreach(_otok_prefix IN LISTS _otok_prefixes)\n"
            "  set(${_otok_prefix}_FOUND TRUE)\n"
            "  set(${_otok_prefix}_LIBRARIES" + quoted_list(targets) + ")\n"
            "  set(${_otok_prefix}_INCLUDE_DIRS ${_otok_include_dirs})\n";
    if (!version.empty()) {
        // digits and dots only (cmake_package_version), at most four parts
        std::array<std::string, 4> parts{"0", "0", "0", "0"};
        std::size_t count = 0;
        for (std::size_t at = 0; count < 4;) {
            std::size_t const dot = version.find('.', at);
            parts[count++] = version.substr(at, dot == std::string::npos ? std::string::npos : dot - at);
            if (dot == std::string::npos) break;
            at = dot + 1;
        }
        text += "  set(${_otok_prefix}_VERSION " + cmake_quoted(version) + ")\n";
        char const* const names[] = {"MAJOR", "MINOR", "PATCH", "TWEAK"};
        for (std::size_t i = 0; i < 4; ++i) text += "  set(${_otok_prefix}_VERSION_" + std::string{names[i]} + " " + parts[i] + ")\n";
        text += "  set(${_otok_prefix}_VERSION_COUNT " + std::to_string(count) + ")\n";
    }
    text += "endforeach()\n";
    for (cmake_name const& v : spec.variables) {
        if (v.include) {
            text += "_otok_cmake_include_dirs(" + v.name + joined_targets(present.contains(v.products.front()) ? v.products : std::vector<std::string>{}) + ")\n";
        } else {
            std::vector<std::string> held;
            for (std::string const& p : v.products) {
                if (present.contains(p)) held.push_back(p);
            }
            text += "set(" + v.name + joined_targets(held) + ")\n";
        }
    }
    text += "\nunset(_otok_name)\nunset(_otok_version)\nunset(_otok_fits)\nunset(_otok_asked)\nunset(_otok_components)\nunset(_otok_missing)\n"
            "unset(_otok_include_dirs)\nunset(_otok_prefixes)\nunset(_otok_prefix)\n";
    return text;
}

std::string version_text(output_package const& o, cmake_package_spec const& spec)
{
    std::string const version = cmake_package_version(o.rec && o.rec->version ? o.rec->version->str() : std::string{});
    std::string text = std::string{generated}
        + "# The version of the CMake package '" + spec.name + "' (otok-toml.md 4.12). Every request is let through to "
        + spec.name + "Config.cmake,\n# which refuses one the library does not meet, so that CMake looks for the package nowhere else.\n\n";
    if (!version.empty()) text += "set(PACKAGE_VERSION " + cmake_quoted(version) + ")\n";
    return text + "set(PACKAGE_VERSION_COMPATIBLE TRUE)\nset(PACKAGE_VERSION_EXACT TRUE)\n";
}

std::string module_text(output_package const& o, cmake_package_spec const& spec)
{
    return std::string{generated} + "# CMake's own search for '" + spec.name + "' once otok's package of " + o.library
        + " was not found (otok-toml.md 4.12):\n# the provider puts this directory first in CMAKE_MODULE_PATH, so that no other " + spec.name
        + " is taken.\n\nset(${CMAKE_FIND_PACKAGE_NAME}_FOUND FALSE)\n";
}

std::string provider_text(std::vector<package_view> const& views, std::span<output_package const> packages)
{
    std::string text = std::string{generated}
        + "# A dependency provider answering find_package with the CMake packages of this output, for CMake 3.28 or later\n"
          "# (otok-toml.md 4.12):\n"
          "#   cmake -DCMAKE_PROJECT_TOP_LEVEL_INCLUDES=<this file> …\n\n"
          "if(CMAKE_VERSION VERSION_LESS 3.28)\n"
          "  message(FATAL_ERROR \"otok: the libraries of ${CMAKE_CURRENT_LIST_DIR} need CMake 3.28 or later\")\n"
          "endif()\n\n"
          "set_property(GLOBAL PROPERTY _otok_provider_dir \"${CMAKE_CURRENT_LIST_DIR}\")\n";
    text += "# the packages, by their names in lower case\n";
    for (package_view const& v : views) {
        text += "set_property(GLOBAL PROPERTY _otok_provider_package_" + cmake_lower(v.spec->name) + " " + cmake_quoted(v.spec->name) + ")\n";
    }
    text += "# the libraries, for the names they give no package of\n";
    for (output_package const& p : packages) {
        text += "set_property(GLOBAL PROPERTY _otok_provider_library_" + p.library + " " + cmake_quoted(p.library) + ")\n";
    }
    text +=
        "\n"
        "macro(_otok_provide_package _otok_provider_method _otok_provider_name)\n"
        "  string(TOLOWER \"${_otok_provider_name}\" _otok_provider_lower)\n"
        "  get_property(_otok_provider_package GLOBAL PROPERTY _otok_provider_package_${_otok_provider_lower})\n"
        "  if(_otok_provider_package)\n"
        "    get_property(_otok_provider_root GLOBAL PROPERTY _otok_provider_dir)\n"
        "    set(_otok_provider_where \"${_otok_provider_root}/" + std::string{cmake_packages_dir} + "/${_otok_provider_package}\")\n"
        "    # the call's version, components and manner kept; where it looks dropped\n"
        "    set(_otok_provider_args \"\")\n"
        "    set(_otok_provider_keep ON)\n"
        "    foreach(_otok_provider_arg IN ITEMS ${ARGN})\n"
        "      if(_otok_provider_arg MATCHES \"^(EXACT|QUIET|REQUIRED|GLOBAL|NO_POLICY_SCOPE|COMPONENTS|OPTIONAL_COMPONENTS)$\")\n"
        "        set(_otok_provider_keep ON)\n"
        "        list(APPEND _otok_provider_args \"${_otok_provider_arg}\")\n"
        "      elseif(_otok_provider_arg MATCHES \"^(MODULE|CONFIG|NO_MODULE|BYPASS_PROVIDER|CMAKE_FIND_ROOT_PATH_BOTH|ONLY_CMAKE_FIND_ROOT_PATH|NO_[A-Z_]+)$\")\n"
        "        set(_otok_provider_keep ON)\n"
        "      elseif(_otok_provider_arg MATCHES \"^(NAMES|CONFIGS|HINTS|PATHS|PATH_SUFFIXES|REGISTRY_VIEW)$\")\n"
        "        set(_otok_provider_keep OFF)\n"
        "      elseif(_otok_provider_keep)\n"
        "        list(APPEND _otok_provider_args \"${_otok_provider_arg}\")\n"
        "      endif()\n"
        "    endforeach()\n"
        "    # CMake's own search after a package not found looks here first too\n"
        "    set(${_otok_provider_name}_DIR \"${_otok_provider_where}\" CACHE PATH \"The CMake package of otok (otok-toml.md 4.12)\" FORCE)\n"
        "    find_package(${_otok_provider_name} ${_otok_provider_args} CONFIG NAMES ${_otok_provider_package}\n"
        "      PATHS \"${_otok_provider_where}\" NO_DEFAULT_PATH NO_CMAKE_FIND_ROOT_PATH BYPASS_PROVIDER)\n"
        "    if(NOT ${_otok_provider_name}_FOUND AND NOT \"${_otok_provider_where}/module\" IN_LIST CMAKE_MODULE_PATH)\n"
        "      list(PREPEND CMAKE_MODULE_PATH \"${_otok_provider_where}/module\")\n"
        "    endif()\n"
        "  else()\n"
        "    get_property(_otok_provider_library GLOBAL PROPERTY _otok_provider_library_${_otok_provider_lower})\n"
        "    get_property(_otok_provider_warned GLOBAL PROPERTY _otok_provider_warned_${_otok_provider_lower})\n"
        "    if(_otok_provider_library AND NOT _otok_provider_warned)\n"
        "      set_property(GLOBAL PROPERTY _otok_provider_warned_${_otok_provider_lower} ON)\n"
        "      get_property(_otok_provider_root GLOBAL PROPERTY _otok_provider_dir)\n"
        "      message(WARNING \"otok: find_package(${_otok_provider_name}) is left to CMake's own search, which may find another \"\n"
        "        \"${_otok_provider_library} than the one of ${_otok_provider_root}: its recipe gives no CMake package of that name; \"\n"
        "        \"name it with 'cmake' in [deps.${_otok_provider_library}] of otok.toml (otok-toml.md 4.12)\")\n"
        "    endif()\n"
        "  endif()\n"
        "  unset(_otok_provider_lower)\n"
        "  unset(_otok_provider_package)\n"
        "  unset(_otok_provider_root)\n"
        "  unset(_otok_provider_where)\n"
        "  unset(_otok_provider_args)\n"
        "  unset(_otok_provider_keep)\n"
        "  unset(_otok_provider_arg)\n"
        "  unset(_otok_provider_library)\n"
        "  unset(_otok_provider_warned)\n"
        "endmacro()\n\n"
        "cmake_language(SET_DEPENDENCY_PROVIDER _otok_provide_package SUPPORTED_METHODS FIND_PACKAGE)\n";
    return text;
}

