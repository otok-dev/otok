// Running `build.lua` for one slice (docs/formats/build-lua-api.md): the `slice`, `options` and `deps`
// tables, the `otok` library and the returned table. The slice is described as data; targets fill it
// (docs/PLAN.md decision 18).
namespace otok {

struct slice_toolchain
{
    std::string cc, cxx, ar, ranlib, strip, nm;                 // paths
    std::string install_name_tool;  // set where dynamic libraries need @rpath/ install names (macOS); empty: none
    std::string rpath;              // the RUNPATH entry of dynamic libraries: "$ORIGIN" on ELF hosts; empty: none
    std::vector<std::string> cflags, cxxflags, ldflags;
    // the flags that choose the machine the compiler builds for, part of its command (build-lua-api.md 3.1): "--target=…";
    // also the first of cflags, cxxflags and ldflags
    std::vector<std::string> driver_flags;
    env_vars env;                                             // what otok.run starts processes with
};

// One entry of `deps` or `deps.tools` (build-lua-api.md 4).
struct slice_dependency
{
    std::filesystem::path prefix;
    std::filesystem::path include;
    std::map<std::string, std::filesystem::path> libraries;
    std::vector<std::filesystem::path> lib_dirs;
    std::filesystem::path bin;                                  // tool dependencies only
    std::string version;
    std::string linkage = "static";
    std::map<std::string, option_data> options;
};

struct slice_context
{
    std::string name;            // "iossim-arm64"
    std::string os;              // "apple"
    std::string platform;        // "iossim"
    std::string arch;            // "arm64"
    // The build environment (build-lua-api.md 3): "linux/clang-cl", the machine "linux-x86_64" and the compiler "clang-cl";
    // empty in a slice of a target without environments, and then nil in `slice`
    std::string environment, host, compiler;
    std::string host_libc;       // "glibc" or "musl" on a Linux build machine, nil in `slice` elsewhere (decision 105)
    std::string triple;          // "arm64-apple-ios15.0-simulator"
    std::string configuration = "release";
    std::string linkage = "static";  // "dynamic" (build-lua-api.md 3)
    std::optional<int> c_standard;          // the project's (otok-toml.md 5.1); none: the recipe chooses
    std::optional<int> cxx_standard;        // the project's (otok-toml.md 5.1); none: the recipe chooses
    // meson's c_std and cpp_std for them (toolchain_profile::meson_standard): "c11", "c++latest"; empty: not set
    std::string meson_c_std, meson_cpp_std;
    bool is_tool = false;        // build_tools
    // the headers slice (build-lua-api.md 3.5): no platform, architecture, configuration, linkage, standards or compiler,
    // which are nil in `slice`; the helpers that compile refuse it
    bool headers = false;

    std::filesystem::path source, build, prefix;   // writable
    std::filesystem::path recipe;                   // read-only
    std::map<std::string, std::filesystem::path> resources;
    std::map<std::string, option_data> vars;
    std::int64_t jobs = 1;
    slice_toolchain toolchain;
    std::optional<std::filesystem::path> tools_prefix;  // slice.tools.prefix
    // slice.toolchains: the programs of the recipe's [toolchains] (recipe-toml.md 13), which the helpers run
    std::map<std::string, std::filesystem::path> toolchains;

    // Target-specific fields of `slice`, given by the target as data (principle 9): strings at the top
    // (`rust_target`, `goos`, …) and tables of strings (`apple = { sdk, sdk_path, … }`).
    std::map<std::string, std::string> target_fields;
    std::map<std::string, std::map<std::string, std::string>> target_tables;

    std::filesystem::path cmake_toolchain;  // generated by the target; empty: none
    std::string autotools_host;             // `--host` of configure; empty: not cross-compiling
    std::string autotools_build;            // `--build` of configure; empty: configure guesses it
    std::string b2_toolset;                 // otok.b2: "darwin", "gcc", …; empty: b2 cannot build the slice
    std::string b2_version = "otok";        // its version in user-config.jam: "14.5" for msvc
    std::vector<std::string> b2_properties; // "target-os=iphone", …
    std::filesystem::path meson_file;       // the machine file the builder wrote; empty: none
    bool meson_cross = false;               // a cross file, else a native file
    std::string meson_system;               // `system` of the cross file's host machine: "android"; empty: native
    std::vector<std::string> meson_options; // the target's: "-Db_vscrt=none"
    std::filesystem::path launcher;         // otok, whose jobserver-exec runs b2's compilers; empty: none

    std::map<std::string, slice_dependency> deps;
    std::map<std::string, slice_dependency> tool_deps;
    std::map<std::string, option_data> options;
    std::vector<std::filesystem::path> option_files;  // the copies file options name, readable (recipe-toml.md 8.3)

    std::filesystem::path log;   // the slice's log: output of processes, otok.log, print
    // Told every command the script starts, with its working directory, before it runs (`otok install -v`); empty: none.
    std::function<void(std::string const& command, std::filesystem::path const& cwd)> echo;
    // Told the stage of every command before it runs, to show it: a helper's ("configure", "build"), or the
    // program's name (command_stage); empty: none.
    std::function<void(std::string const& stage)> stage;

    // Starts processes; tests replace it to record what would run.
    std::function<result<process_exit>(process_spec const&)> run = run_process;
    // How `tool` ("make", "ninja") in the PATH of `env` takes the jobserver of MAKEFLAGS (build-lua-api.md 6.2); the
    // builder caches the answers, tests replace it.
    std::function<jobserver_protocol(std::string const& tool, env_vars const& env)> jobserver_client = jobserver_protocol_of;
    // For a tool without the jobserver, which runs a fixed number of jobs: how many it may run now, at most `most`, and
    // what gives them back when it ends (docs/PLAN.md decision 61); empty: `most`.
    std::function<std::pair<std::int64_t, std::function<void()>>(std::int64_t most)> hold_jobs;
};

enum class build_entry
{
    build,       // build(slice, options, deps)
    build_tools   // build_tools(slice, options, deps), optional
};

// What `build` returned (build-lua-api.md 8), paths checked to exist inside slice.prefix.
struct build_output
{
    std::map<std::string, std::filesystem::path> libraries;            // the files linked against
    std::map<std::string, std::filesystem::path> runtimes;             // DLLs of import libraries
    std::map<std::string, std::filesystem::path> symbols;              // their .pdb files
    std::optional<std::filesystem::path> headers;                       // one directory for all
    std::map<std::string, std::filesystem::path> library_headers;       // or one per library
    std::optional<std::filesystem::path> module_map;
    std::map<std::string, std::filesystem::path> library_module_maps;
    std::map<std::string, std::filesystem::path> data;                 // files shipped beside the libraries
    std::map<std::string, std::filesystem::path> programs;             // a tool recipe's (recipe-toml.md 3.1)
    std::map<std::string, std::string> interpreters;                   // program → the toolchain its script runs under (docs/PLAN.md decision 70)
    std::vector<std::string> warnings;                                  // otok.warn
};

// Whether the script defines the global function `name` (its top level only defines functions,
// build-lua-api.md 2), e.g. to know before building whether there is a `build_tools`.
result<bool> script_defines(std::filesystem::path const& script, std::string const& label, std::string const& name);

// Runs `entry` of the script `script` (named `label` in messages) for the slice. For build_tools a
// script without the function does nothing, and the returned value is ignored.
result<build_output> run_build_script(std::filesystem::path const& script, std::string const& label, build_entry entry,
    slice_context const& slice);

}
